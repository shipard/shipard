<?php

declare(strict_types=1);

namespace Shipard\Tests\Unit\Core\Server;

use PHPUnit\Framework\TestCase;
use Shipard\Core\Server\DevHttpsSite;

/** Render site souboru https vstupů ze skutečné šablony (#183 D4, U6). */
class DevHttpsSiteTest extends TestCase
{
    private const string SOCKET = '/run/php/php8.5-fpm-shipard.sock';

    private function template(): string
    {
        return (string) file_get_contents(dirname(__DIR__, 4) . '/docs/nginx/development-https.conf');
    }

    /** Direktivy bez komentářů. */
    private function directives(string $site): string
    {
        return preg_replace('/#[^\n]*/', '', $site) ?? '';
    }

    public function testNoBlockMeansNoSite(): void
    {
        $this->assertNull(DevHttpsSite::render($this->template(), false, null, self::SOCKET, true));
    }

    public function testIpBlockOnly(): void
    {
        $site = (string) DevHttpsSite::render($this->template(), true, null, self::SOCKET, false);
        $directives = $this->directives($site);

        $this->assertSame(1, substr_count($directives, 'server {'));
        $this->assertStringContainsString('listen 443 ssl default_server;', $directives);
        $this->assertStringContainsString('/etc/shipard/tls/dev-ip/fullchain.pem', $directives);
        $this->assertStringNotContainsString('dev-host', $site);
        $this->assertStringNotContainsString('__SERVER_NAME__', $site);
        // Vypnutý vstup nezanechá ani značky.
        $this->assertStringNotContainsString('>>>', $site);
        $this->assertStringNotContainsString('<<<', $site);
    }

    public function testHostBlockOnly(): void
    {
        $site = (string) DevHttpsSite::render($this->template(), false, 'shpd.example.com', self::SOCKET, false);
        $directives = $this->directives($site);

        $this->assertSame(1, substr_count($directives, 'server {'));
        $this->assertStringContainsString('server_name shpd.example.com;', $directives);
        $this->assertStringContainsString('/etc/shipard/tls/dev-host/privkey.pem', $directives);
        $this->assertStringNotContainsString('default_server', $directives);
        $this->assertStringNotContainsString('dev-ip', $directives);
    }

    public function testBothBlocksWithSocketAndWithoutHsts(): void
    {
        $site = (string) DevHttpsSite::render($this->template(), true, 'shpd.example.com', self::SOCKET, true);
        $directives = $this->directives($site);

        $this->assertSame(2, substr_count($directives, 'server {'));
        $this->assertSame(2, substr_count($directives, 'fastcgi_pass unix:' . self::SOCKET . ';'));
        $this->assertStringNotContainsString('/run/php/php-fpm.sock', $site);
        $this->assertSame(2, substr_count($directives, 'shipard-tls-params.conf'));
        $this->assertStringNotContainsString('shipard-tls.conf', $directives);
        $this->assertStringNotContainsString('Strict-Transport-Security', $site);
        $this->assertSame(2, substr_count($directives, 'development-locations.conf'));
        $this->assertStringStartsWith('# Generated by `shpd-server dev-https`', $site);
        $this->assertStringEndsWith("}\n", $site);
    }

    public function testIpv6ListenLinesOnlyWithIpv6(): void
    {
        $with = (string) DevHttpsSite::render($this->template(), true, 'shpd.example.com', self::SOCKET, true);
        $without = (string) DevHttpsSite::render($this->template(), true, 'shpd.example.com', self::SOCKET, false);

        $this->assertStringContainsString('listen [::]:443 ssl default_server;', $with);
        $this->assertStringContainsString("listen [::]:443 ssl;\n", $with);
        $this->assertStringNotContainsString('# ipv6', $with, 'značka generátoru se do site souboru nepřenáší');

        $this->assertStringNotContainsString('[::]', $without);
        $this->assertStringContainsString('listen 443 ssl default_server;', $without);
    }

    public function testRenderIsDeterministic(): void
    {
        // --check a doctor porovnávají soubor na disku s renderem.
        $this->assertSame(
            DevHttpsSite::render($this->template(), true, 'shpd.example.com', self::SOCKET, true),
            DevHttpsSite::render($this->template(), true, 'shpd.example.com', self::SOCKET, true),
        );
    }

    public function testRejectsValuesThatDoNotBelongToNginxConfig(): void
    {
        foreach (['shpd.example.com; include /etc/passwd', '*.example.com', 'a b', '10.0.0.7'] as $host) {
            try {
                DevHttpsSite::render($this->template(), false, $host, self::SOCKET, false);
                $this->fail("host '{$host}' měl být odmítnut");
            } catch (\InvalidArgumentException $e) {
                $this->assertStringContainsString('Not a host name', $e->getMessage());
            }
        }

        $this->expectException(\InvalidArgumentException::class);
        DevHttpsSite::render($this->template(), true, null, '/run/php/x.sock; }', false);
    }

    public function testTemplateWithoutBlockIsAnError(): void
    {
        $this->expectException(\InvalidArgumentException::class);
        $this->expectExceptionMessage("no 'https-ip' block");
        DevHttpsSite::render("server { listen 443 ssl; }\n", true, null, self::SOCKET, false);
    }
}
