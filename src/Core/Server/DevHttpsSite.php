<?php

declare(strict_types=1);

namespace Shipard\Core\Server;

/**
 * Site soubor https vstupů vývojového serveru (#183 D4, U6) — čistý render
 * šablony `docs/nginx/development-https.conf`:
 *
 * - blok mezi řádky `# >>> https-ip` / `# <<< https-ip` zůstane, jen když
 *   je zapnutý vstup přes IP; `https-host` jen se jménem;
 * - řádky končící `# ipv6` jen se zapnutým IPv6;
 * - `__SERVER_NAME__` → jméno, `fastcgi_pass unix:/run/php/…;` → socket
 *   poolu shipard (stejné pravidlo jako `install-packages.sh`).
 *
 * Výstup je deterministický (bez data), aby `dev-https --check` a `doctor`
 * mohly porovnat soubor na disku s tím, co by běh zapsal. Text mimo značky
 * (hlavička šablony) se do site souboru nepřenáší.
 */
final class DevHttpsSite
{
    public const string FILE_NAME = 'shipard-https.conf';
    public const string BLOCK_IP = 'https-ip';
    public const string BLOCK_HOST = 'https-host';

    private const string HEADER = "# Generated by `shpd-server dev-https` from docs/nginx/development-https.conf\n"
        . "# and `devAccess` in /etc/shipard/server.json. Do not edit — the next run overwrites it.\n"
        . "# Regenerate: sudo shpd-server dev-https\n";

    /**
     * @param ?string $host jméno pro blok https-host; null = blok se vynechá
     * @return ?string obsah site souboru; null = žádný blok není zapnutý
     *
     * @throws \InvalidArgumentException šablona nemá požadovaný blok nebo jméno není jméno hostu
     */
    public static function render(string $template, bool $ipBlock, ?string $host, string $socket, bool $ipv6): ?string
    {
        if ($host !== null && !DevAccess::isHostName($host)) {
            throw new \InvalidArgumentException("Not a host name: {$host}");
        }
        if (preg_match('#^/[A-Za-z0-9._/-]+$#', $socket) !== 1) {
            throw new \InvalidArgumentException("Not a socket path: {$socket}");
        }

        $blocks = [];
        if ($ipBlock) {
            $blocks[] = self::block($template, self::BLOCK_IP);
        }
        if ($host !== null) {
            $blocks[] = str_replace('__SERVER_NAME__', $host, self::block($template, self::BLOCK_HOST));
        }
        if ($blocks === []) {
            return null;
        }

        $out = [];
        foreach (explode("\n", implode("\n\n", $blocks)) as $line) {
            if (preg_match('/^(.*?;)\s*# ipv6\s*$/', $line, $m) === 1) {
                if ($ipv6) {
                    $out[] = $m[1];
                }
                continue;
            }
            $out[] = $line;
        }
        $body = preg_replace(
            '#fastcgi_pass unix:/run/php/[^;]*;#',
            'fastcgi_pass unix:' . $socket . ';',
            implode("\n", $out),
        ) ?? '';

        return self::HEADER . "\n" . $body . "\n";
    }

    /** Tělo bloku mezi značkami (bez řádků značek). */
    private static function block(string $template, string $name): string
    {
        $lines = explode("\n", str_replace("\r\n", "\n", $template));
        $start = array_search('# >>> ' . $name, $lines, true);
        $end = array_search('# <<< ' . $name, $lines, true);
        if ($start === false || $end === false || $end <= $start) {
            throw new \InvalidArgumentException("Template has no '{$name}' block");
        }
        return trim(implode("\n", array_slice($lines, $start + 1, $end - $start - 1)), "\n");
    }
}
